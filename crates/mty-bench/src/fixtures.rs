//! Shared fixtures for the v0.6 benchmark suite.
//!
//! The synthetic 10 KLOC Mighty source is generated deterministically
//! so the parse_throughput numbers are reproducible across machines.
//! See `docs/internals/benchmarking.md` for the format.

use std::sync::Arc;

/// Build a deterministic ~10 000-line Mighty source. The shape mixes
/// declarations the lexer + parser exercise heavily (structs, fns,
/// enums, match arms, let-bindings, arithmetic) so it's a realistic
/// proxy for "tooling baseline" work rather than a pathological worst
/// case.
///
/// Output line count for the default `units = 1000` is 10 002 lines
/// (10 lines per unit + 2 lines of header).
pub fn stardust_10kloc() -> String {
    synth_source(1000)
}

/// Approximate line count of `stardust_10kloc()`. Cheap helper for
/// scaling throughput numbers without re-counting.
pub fn ten_kloc_lines() -> usize {
    10 * 1000 + 2
}

/// Build a Mighty source of `units` × 10 lines. Each unit declares
/// one struct + one fn — deterministic so two runs of the same build
/// see identical input.
///
/// The struct prefix (`Rec`) and fn prefix (`bench_f`) are chosen to
/// avoid collisions with WIT reserved names (`s8`, `f32`, etc.) when
/// the source is sent down the wasm compile pipeline.
pub fn synth_source(units: usize) -> String {
    let mut out = String::with_capacity(units * 256);
    out.push_str("// auto-generated by mty-bench synth_source\n");
    out.push_str("// units = ");
    out.push_str(&units.to_string());
    out.push('\n');
    for i in 0..units {
        // 10 lines per unit; keep the shape identical so the lexer
        // hits a uniform mix of identifier/keyword/number/punctuator
        // tokens.
        let _ = std::fmt::Write::write_fmt(
            &mut out,
            format_args!(
                "struct Rec{i} {{\n  id: I64\n  name: I64\n  flag: I64\n}}\n\
fn bench_f{i}(x: I64, y: I64) -> I64 {{\n  let z = x + y\n  let w = z * 2 - x\n  w\n}}\n"
            ),
        );
    }
    out
}

/// A tiny `agent Echo` SIR program (parsed + lowered once per call).
/// Used by the agent/mailbox benchmarks so the per-iter cost only
/// measures send / dispatch, not parsing.
pub fn echo_sir_program() -> Arc<mty_ir::ir::Program> {
    let src = r#"
protocol Echo {
  Ping(msg: I64) -> I64
}

agent Echoer: Echo {
  on Ping(msg) -> msg
}
"#;
    let parsed = mty_driver::parse_source(src.to_string(), "echo.mty".into());
    let (pkg, _diags) = mty_driver::lower(&parsed);
    let typed = mty_types::check_package_typed(&pkg);
    Arc::new(mty_ir::lower_package(&pkg, &typed))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn synth_source_is_deterministic() {
        let a = stardust_10kloc();
        let b = stardust_10kloc();
        assert_eq!(a, b);
    }

    #[test]
    fn ten_kloc_close_to_target() {
        let s = stardust_10kloc();
        let n = s.lines().count();
        // tolerate ±10 lines of header drift
        assert!((10_000..=10_050).contains(&n), "got {n} lines");
    }
}
